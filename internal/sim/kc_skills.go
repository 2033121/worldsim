// EventDesignSkills 返回事件设计类方法论精华（注入事件Agent）
// 从 KC-SKILL 系列方法论卡片中提取核心操作指令，适配为 WorldSim prompt 风格
func EventDesignSkills() string {
	return `
16. 冲突深化（冲突四类型进阶）：
   · 人与自我：道德抉择/自我怀疑/过去阴影——主角内心撕裂时，生成一个让主角"必须做选择"的事件
   · 人与人：目标冲突/观念冲突/资源冲突/情绪冲突——冲突双方都要有合理动机，不能一方纯粹是坏人
   · 人与社会：制度/权力/阶层——主角与规则碰撞时，规则背后要有利益链条
   · 冲突升级链：小摩擦→误解→对立→不可调和——别一步跳到打斗，让矛盾有发酵过程
17. 钩子九连环（每天至少一个）：
   · 悬念钩：抛出反常现象让读者好奇"为什么"
   · 反差钩：与预期完全相反的场景/人物出现
   · 危机钩：直接威胁主角的安全/地位/关系
   · 金手指钩：主角能力的异常表现或新发现
   · 情感钩：关系突变——心动/背叛/重逢/误会
   · 谜题钩：一个待解的怪事，线索指向未知
   · 平淡日的钩子要"轻"：一句怪话/一个反常细节/一个"不对劲"，不用展开，种子埋下就行
18. 悬念信息控制（悬念=未知性×关注度×持续性）：
   · 信息差分层：主角知道什么、读者知道什么、NPC知道什么——三层信息差同时存在时悬念最强
   · 揭示节奏：给一点线索→读者以为猜到了→反转→给更多线索——别一次揭底
   · 悬念保鲜：长线悬念每隔几章"提醒"一次（主角想起/新线索出现），别埋了就忘
19. 爽点节奏（爽感=铺垫长度×反差强度×读者代入度）：
   · 爽点四类交替用：打脸类（被看不起→实力碾压）/收获类（得到关键道具/能力/盟友）/装逼类（深藏不露→一鸣惊人）/情感类（误解消除/守护成功）
   · 密度控制：连憋3-5天后必须给一次释放，释放后给2-3天平稳期再开始下一轮蓄力
   · 铺垫→蓄力→爆发三步缺一不可，没有铺垫的爆发是"主角开挂"，读者反感
20. 人物弧光与高燃设计：
   · 每个重要NPC给三位一体记忆锚点：视觉标签（独一无二的外形特征）+口头禅（标志性台词）+行为标签（独特行为模式）
   · 人设反差：外在表现反衬内在执念（强的衬痛/弱的衬刚/柔的衬刚/亮的衬孤）
   · 高燃时刻：主角在绝境中做出符合核心主题的选择——不是"突然变强"，是"一直在忍，终于不忍了"
21. 智斗博弈（适用于冲突/quest/mystery/rival事件）：
   · 双方都有智商：对手有底牌有算计，不靠降智衬托主角
   · 信息不对称：你知道的/我知道的/你以为我知道的——三层信息差驱动博弈
   · 反转逻辑：意料之外情理之中——回头看全是伏笔，不是突然开挂
22. 伏笔系统进阶（伏笔体验感=隐蔽度×回收惊喜感×前后呼应度）：
   · 埋设要"随手"：伏笔第一次出现时看起来是无关紧要的细节（一个动作/一句闲话/一个物件），不能让读者察觉"这是伏笔"
   · 回收要"恍然"：回收时读者才意识到那个细节的意义——拍大腿的感觉
   · 酝酿度推进：每次"推进"伏笔只露一点点新信息，别一次性揭底
   · 短线伏笔（1-3天）必须快速回收，别积压；长线伏笔每5-7天"提醒"一次存在感`
}

// WritingCraftSkills 返回写作技法类方法论精华（注入小说写手）
// 从 KC-SKILL 系列方法论卡片中提取核心操作指令，适配为 WorldSim prompt 风格
func WritingCraftSkills() string {
	return `
去AI味进阶（真人编辑方法论，违反=本章不合格）：
7. AI高频词深度替换：突然→猛地/冷不丁/说时迟那时快；缓缓→动作慢得像xxx；微微→ barely perceptible替代；似乎→用具体感官替代（"似乎有人"→"后脖颈一阵凉"）。本章AI高频词超过3次判为不合格。
8. 统计概率反转：每写1000字找3个"最安全的词"换成"不那么常用但更准确"的词；每个比喻问"AI会用这个比喻吗"，是就换掉；每个剧情节点想"AI会怎么写"，然后反着写（只要逻辑自洽）。
9. 混沌感注入：每章至少留1个"不解释"的细节（主角为什么讨厌猫？不解释）；允许角色偶尔做出"不符合人设"的举动（人是复杂的）；故意留一些"没用"的细节——真实生活里很多事就是没用的。
10. 情绪毛刺：每个强烈情绪混入一点相反情绪（开心时一丝怅然，愤怒时一丝无力）；情绪转变要有"卡顿"——变了一下又退回去再变；设计个人化情绪反应（紧张会笑/难过会吃东西）。

感官描写五维法（每场景≥4维）：
· 视觉：必有，含至少1个反常细节（不该出现的东西/不该有的颜色/不该在的位置）
· 听觉：环境音+人声——不是"很吵"，是"铁皮在风里哗哗响，混着发电机嗡嗡"
· 触觉：温度/质感/疼痛——"手心贴上去是冰的，像摸一块湿玻璃"
· 嗅觉：气味是记忆触发器——"海水腥咸混着铁锈，和小时候外婆家那个铁罐子一个味"
· 第六感：后脖颈发凉/胃里翻涌/汗毛竖起/莫名的违和感——用在关键时刻，不是每段都有

对话技法进阶：
· 对白五句式：陈述句（给信息）/反问句（施压）/省略句（留白）/动作句（带行为）/沉默句（用动作代替回答）——五种交替用，别一直陈述
· 对话要有潜台词：角色嘴上说的和心里想的不一样——"你吃了吗"可能是"我想你了"，"随便"可能是"我很在意"
· 打岔与插话：真实对话不是一问一答——人会插嘴、跑题、答非所问、说一半不说了
· 对话带性格：毒舌的呛人/温柔的话软/沉默的惜字如金/话多的东拉西扯——一句话能带出角色是谁

节奏控制公式：
· 紧张度曲线：每章必须有一个"峰"（高潮场景）和一个"谷"（缓冲/反思），不能从头紧到尾
· 时间弹性：紧张场景放慢写（1分钟的事写500字），平淡场景快进（3天的事一句话带过）
· 段落节奏：短段（1-2行）制造紧张感，长段（4-5行）用于铺垫和氛围——交替使用，别全是短段或全是长段
· 信息密度：每段必须带新信息（动作/对话/环境/心理），删掉不带新信息的段落

记忆钉系统（让读者记住关键场景）：
· 每章钉1-2个"记忆钉"：一个极具画面感的瞬间（一个动作/一句台词/一个画面），读者读完几天后还能想起来
· 记忆钉的特征：具体（不是"很感动"而是"他蹲下来把碎掉的杯子一片片捡起来"）+反常（超出日常预期）+情感锚定（带情绪共振）

崩文预防检查（每章自检）：
· 主角是否在主动推动剧情？（被动=崩文前兆）
· 是否有角色做出与设定矛盾的事？（OOC=读者出戏）
· 是否有"为了剧情需要"而强行安排的巧合？（机械降神=读者反感）
· 本章结尾是否比开头有新的信息/变化？（没有=水章）`
}
